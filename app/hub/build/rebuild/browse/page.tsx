import Link from "next/link";
import { auth } from "@clerk/nextjs/server";
import { getOrCreateProfile, isFounder } from "@/lib/member";
import { getBuildReps } from "@/lib/build";
import { aiConfigured } from "@/lib/ai";
import { catalogueCareers, catalogueForCareer } from "@/lib/rebuild-catalogue";
import { memberLane } from "@/lib/gym-generate";
import { RebuildCareerPicker } from "@/components/hub/build/RebuildCareerPicker";
import { SeedCatalogue } from "@/components/hub/build/SeedCatalogue";

export const metadata = { title: "Rebuild catalogue — Pivotum" };

export default async function RebuildBrowse({ searchParams }: { searchParams: Promise<{ career?: string }> }) {
  const { userId } = await auth();
  const [{ career: qCareer }, profile, cats, done, seed] = await Promise.all([
    searchParams,
    getOrCreateProfile(),
    catalogueCareers(),
    getBuildReps(userId),
    memberLane(userId),
  ]);
  const founder = isFounder(profile);

  const inCat = (name?: string | null) => name && cats.some((c) => c.career.toLowerCase() === name.toLowerCase());
  const selected =
    (qCareer && inCat(qCareer) && cats.find((c) => c.career.toLowerCase() === qCareer.toLowerCase())?.career) ||
    (inCat(seed?.career) && seed?.career) ||
    (inCat(seed?.lane) && seed?.lane) ||
    cats[0]?.career ||
    null;

  const reps = selected ? await catalogueForCareer(selected) : [];

  return (
    <>
      <div className="hub-toolbar"><Link href="/hub/build/rebuild" className="back">‹ Workflow Rebuild</Link><span className="tt">Catalogue</span></div>
      <div className="hub-body">
        <div className="build-hero">
          <p className="ck">🗂 The Rebuild catalogue</p>
          <h2>Every workflow rebuild, by career.</h2>
          <p>Search for a field and see every workflow rebuilt for it — the hand-built ones and the shared rebuilds generated by the community. New ones get added to the pool as members train.</p>
        </div>

        {founder && aiConfigured() && <SeedCatalogue endpoint="/api/hub/rebuild-seed" noun="rebuild" />}

        {cats.length === 0 ? (
          <p className="feed-empty">No rebuilds in the catalogue yet.</p>
        ) : (
          <>
            <div className="gymcat-bar">
              <RebuildCareerPicker careers={cats.map((c) => ({ career: c.career, total: c.total }))} current={selected ?? undefined} />
              <span className="gymcat-count">{cats.length} careers · {cats.reduce((n, c) => n + c.total, 0)} rebuilds</span>
            </div>

            {selected && (
              <>
                <div className="hub-sectlabel">{selected} · {reps.length} rebuild{reps.length === 1 ? "" : "s"}</div>
                <div className="hub-grid">
                  {reps.map((r, i) => {
                    const href = r.kind === "authored" ? `/hub/build/rebuild/${r.careerSlug}/${r.slug}` : `/hub/build/rebuild/g/${r.id}`;
                    const key = r.kind === "authored" ? `rebuild:${r.slug}` : `rebuild:gen-${r.id}`;
                    const isDone = done.has(key);
                    return (
                      <Link key={i} href={href} className="card gym-card">
                        <p className="ck">🔧 {r.kind === "authored" ? "Core rebuild" : "Community rebuild"}{isDone ? " · done ✓" : ""}</p>
                        <h3>{r.variant.title}</h3>
                        <p>{r.variant.short}</p>
                      </Link>
                    );
                  })}
                </div>
              </>
            )}
          </>
        )}
      </div>
    </>
  );
}
