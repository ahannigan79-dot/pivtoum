import Link from "next/link";
import { auth } from "@clerk/nextjs/server";
import { getOrCreateProfile, isFounder } from "@/lib/member";
import { getBuildReps } from "@/lib/build";
import { aiConfigured } from "@/lib/ai";
import { catalogueCareers, catalogueForCareer } from "@/lib/gym-catalogue";
import { memberLane } from "@/lib/gym-generate";
import { GymCareerPicker } from "@/components/hub/build/GymCareerPicker";
import { SeedCatalogue } from "@/components/hub/build/SeedCatalogue";

export const metadata = { title: "Gym catalogue — Pivotum" };

export default async function GymBrowse({ searchParams }: { searchParams: Promise<{ career?: string }> }) {
  const { userId } = await auth();
  const [{ career: qCareer }, profile, cats, done, seed] = await Promise.all([
    searchParams,
    getOrCreateProfile(),
    catalogueCareers(),
    getBuildReps(userId),
    memberLane(userId),
  ]);
  const founder = isFounder(profile);

  const inCat = (name?: string | null) => name && cats.some((c) => c.career.toLowerCase() === name.toLowerCase());
  const selected =
    (qCareer && inCat(qCareer) && cats.find((c) => c.career.toLowerCase() === qCareer.toLowerCase())?.career) ||
    (inCat(seed?.career) && seed?.career) ||
    (inCat(seed?.lane) && seed?.lane) ||
    cats[0]?.career ||
    null;

  const reps = selected ? await catalogueForCareer(selected) : [];

  return (
    <>
      <div className="hub-toolbar"><Link href="/hub/build/gym" className="back">‹ Judgment Gym</Link><span className="tt">Catalogue</span></div>
      <div className="hub-body">
        <div className="build-hero">
          <p className="ck">🗂 The Gym catalogue</p>
          <h2>Every rep, by career.</h2>
          <p>Search for a field and work through every scenario in it — the hand-built ones and the shared reps generated by the community. New reps get added to the pool as members train.</p>
        </div>

        {founder && aiConfigured() && <SeedCatalogue />}

        {cats.length === 0 ? (
          <p className="feed-empty">No reps in the catalogue yet.</p>
        ) : (
          <>
            <div className="gymcat-bar">
              <GymCareerPicker careers={cats.map((c) => ({ career: c.career, total: c.total }))} current={selected ?? undefined} />
              <span className="gymcat-count">{cats.length} careers · {cats.reduce((n, c) => n + c.total, 0)} reps</span>
            </div>

            {selected && (
              <>
                <div className="hub-sectlabel">{selected} · {reps.length} rep{reps.length === 1 ? "" : "s"}</div>
                <div className="hub-grid">
                  {reps.map((r, i) => {
                    const href = r.kind === "authored" ? `/hub/build/gym/${r.slug}` : `/hub/build/gym/g/${r.id}`;
                    const key = r.kind === "authored" ? `gym:${r.slug}` : `gym:gen-${r.id}`;
                    const isDone = done.has(key);
                    return (
                      <Link key={i} href={href} className="card gym-card">
                        <p className="ck">🥊 {r.kind === "authored" ? "Core rep" : "Community rep"}{isDone ? " · done ✓" : ""}</p>
                        <h3>{r.scenario.client}</h3>
                        <p>{r.scenario.short}</p>
                      </Link>
                    );
                  })}
                </div>
              </>
            )}
          </>
        )}
      </div>
    </>
  );
}
